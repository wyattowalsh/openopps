def _dataset_description() -> str:
    return """# OpenOppsDB

OpenOppsDB is a versioned public hiring-board ledger generated by the OpenOpps CLI. It tracks discovered company boards, executable provider routes, normalized job identities, versioned job content, raw provider payload snapshots, and sync observations over time.

## What is included

- `openoppsdb.sqlite`: the OpenOppsDB SQLite database file, including metadata tables named `openopps_tables` and `openopps_columns`.
- `exports/csv/*.csv`: full table exports for spreadsheet and lightweight analysis workflows, including rendered HTML descriptions, structured job-description JSON, and raw payloads.
- `exports/parquet/*.parquet`: full table exports for Python, DuckDB, Polars, Spark, and warehouse workflows, including rendered HTML descriptions, structured job-description JSON, and raw payloads.

## How updates work

The connected Kaggle notebook `openoppsdb-manager` is intended to run once per day on a Kaggle cron schedule. Each run installs OpenOpps from GitHub, copies the current public `openoppsdb.sqlite` snapshot from this dataset, restores large columns from prior Parquet exports only when upgrading legacy thin snapshots, rehydrates the public SQLite snapshot into a fresh operational Alembic schema when needed, runs bounded `openopps jobs sync --metrics-json --freshness-seconds --limit`, and captures private run evidence for the quality gate. It then invokes `python -m openopps_kaggle` to backfill derived skill tables, export every SQLite table to CSV and Parquet, regenerate Kaggle field metadata, write the public SQLite metadata tables, prune private manager evidence, stage the public upload directory, and attempt best-effort live Kaggle file metadata repair after publish. Local maintainer runs of `just kaggle-live-file-metadata` use browser-authenticated cookies for the authoritative Kaggle DataBundle checklist and column-score repair. The public file surface is intentionally limited to `openoppsdb.sqlite`, `exports/csv/*.csv`, and `exports/parquet/*.parquet`.

## Quick start

```python
import sqlite3
import polars as pl

conn = sqlite3.connect('/kaggle/input/openoppsdb/openoppsdb.sqlite')
jobs = pl.read_database('select * from jobs limit 10', conn)
versions = pl.read_parquet('/kaggle/input/openoppsdb/exports/parquet/job_versions.parquet')
```

## Notes and limitations

OpenOpps only uses public endpoints and public pages. Provider payloads are preserved for auditability, but normalized fields should be treated as best-effort public-data extraction rather than official ATS records. Kaggle renders CSV and Parquet exports as the primary tabular preview and column-metadata surfaces; if Kaggle does not expose nested SQLite table previews for a fresh upload, open the SQLite file directly or use the mirrored CSV/Parquet exports. A row can appear across multiple source catalogs; durable keys and sync observation tables are provided so downstream users can reason about provenance and change history.

Public publish quality gates hard-block oversize artifacts (SQLite above 2 GiB or combined CSV/Parquet exports above 4 GiB) so manager notebook disk limits are not exceeded silently. Local maintainer create/version recipes rebuild from an explicit clean-schema DB path before staging; do not upload legacy ledgers that still carry removed columns such as `sources.enabled`.
"""


